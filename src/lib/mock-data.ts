// Helper to generate current month's attendance records
export function generateMonthAttendance(employeeId: string = 'e0000001-0000-0000-0000-000000000003'): AttendanceRecord[] {
  const records: AttendanceRecord[] = [];
  const daysInAugust = 22; // up to today (Aug 22, 2026)

  for (let i = 1; i <= daysInAugust; i++) {
    const dayStr = i.toString().padStart(2, '0');
    const dateStr = `2026-08-${dayStr}`;
    const dateObj = new Date(`2026-08-${dayStr}T00:00:00Z`);
    const dayOfWeek = dateObj.getUTCDay(); // 0 = Sun, 6 = Sat

    if (dayOfWeek === 0 || dayOfWeek === 6) {
      records.push({
        id: `att-202608${dayStr}`,
        employee_id: employeeId,
        date: dateStr,
        check_in: null,
        check_out: null,
        duration_hours: 0,
        status: 'WEEKEND',
        notes: 'Weekend',
      });
      continue;
    }

    if (i === 15) {
      // Independence Day
      records.push({
        id: `att-202608${dayStr}`,
        employee_id: employeeId,
        date: dateStr,
        check_in: null,
        check_out: null,
        duration_hours: 0,
        status: 'HOLIDAY',
        notes: 'Independence Day',
      });
      continue;
    }

    if (i === 7) {
      // Half-day
      records.push({
        id: `att-202608${dayStr}`,
        employee_id: employeeId,
        date: dateStr,
        check_in: `2026-08-${dayStr}T09:15:00.000Z`,
        check_out: `2026-08-${dayStr}T13:45:00.000Z`,
        duration_hours: 4.5,
        status: 'HALF_DAY',
        notes: 'Medical checkup in second half',
      });
      continue;
    }

    if (i === 18) {
      // Sick leave
      records.push({
        id: `att-202608${dayStr}`,
        employee_id: employeeId,
        date: dateStr,
        check_in: null,
        check_out: null,
        duration_hours: 0,
        status: 'ON_LEAVE',
        notes: 'Approved Casual Leave',
      });
      continue;
    }

    if (i === 22) {
      // Today! Checked in at 9:02 AM
      records.push({
        id: `att-202608${dayStr}`,
        employee_id: employeeId,
        date: dateStr,
        check_in: `2026-08-${dayStr}T09:02:00.000Z`,
        check_out: null,
        duration_hours: 6.2,
        status: 'PRESENT',
        notes: 'In Office - Bellandur Hub',
      });
      continue;
    }

    // Normal present day
    const randomMins = 5 + (i % 25);
    records.push({
      id: `att-202608${dayStr}`,
      employee_id: employeeId,
      date: dateStr,
      check_in: `2026-08-${dayStr}T09:${randomMins < 10 ? '0' + randomMins : randomMins}:00.000Z`,
      check_out: `2026-08-${dayStr}T18:${randomMins < 10 ? '0' + randomMins : randomMins}:00.000Z`,
      duration_hours: 8.5 + (i % 2 === 0 ? 0.3 : -0.2),
      status: 'PRESENT',
      notes: 'Logged via Biometric Gate 2',
    });
  }

  return records;
}

